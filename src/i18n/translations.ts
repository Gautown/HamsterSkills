/**
 * 界面文案语言包。
 *
 * 结构约定：
 *   - 五个 locale（zh / zh-tw / en / ko / ms）键集合必须完全一致，
 *     由 scripts/i18n.test.mjs 强制检查（构建前拦截「只加一边」）；
 *   - 文案里 {n} {total} {shown} {title} 等是运行时占位符，
 *     客户端脚本按字符串替换填值，两侧（各语言）都要保留同名占位符；
 *   - en 与 ms 的 gradeSuffix 允许空串（渲染走独立的 "Grade X" 分支），
 *     其余键一律不能为空。
 *
 * 技能本体（标题/描述/正文）不在语言包里：zh/zh-tw 用中文数据，
 * en/ko/ms 用英文数据（见 SkillCard / SkillDetail 的内容语言分支）。
 */
export type Locale = 'zh' | 'zh-tw' | 'en' | 'ko' | 'ms'

/**
 * 把 {key} 占位符模板填充为最终文案（含变量的描述模板五语言共用同一变量集）。
 * 只替换已传入的键：漏传时占位符原样保留，
 * 会让渲染结果带着肉眼可见的 `{tag}`，比静默渲染空串更容易在预览时发现。
 */
export function fillPlaceholders(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (raw, key) => (key in vars ? String(vars[key]) : raw))
}

